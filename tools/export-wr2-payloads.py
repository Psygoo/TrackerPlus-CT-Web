#!/usr/bin/env python3
"""Build the browser's project-owned WR2 payload module from source.

Requires Python 3 and Arm GNU Toolchain 15.2.Rel1. It reads no firmware.
"""
import argparse,hashlib,json,subprocess,tempfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'wr2/payload-src'; OUT=ROOT/'wr2/generated/payloads.js'
def main():
 p=argparse.ArgumentParser();p.add_argument('--compiler',required=True,type=Path);p.add_argument('--check',action='store_true');a=p.parse_args()
 specs={
  'wr1':(['gateway.S','weighted_random.c'],'link.ld','wr1',['-Os','-mcpu=cortex-m7','-mthumb','-mfloat-abi=soft','-ffreestanding','-fno-builtin','-fno-unwind-tables','-fno-asynchronous-unwind-tables','-fstack-usage'],['gateway.S'],True),
  'ui':(['ui_page.S','group_add.c','weight.c','playback.c','playback_gateway.S'],'link.ld','ui',[],['ui_page.S','playback_gateway.S'],True),
  'address':(['patch.S'],'patch.ld','address',[],['patch.S'],False),
 }
 for n in ['s11b','s12a','s12b','s12c']:
  cfg=json.loads((SRC/n/'settings.json').read_text());specs[n]=(cfg['SOURCES'],'payload.ld',n,[],[],False)
 out={}
 def run(tool,*args):return subprocess.check_output([str(a.compiler/('arm-none-eabi-'+tool)),*map(str,args)],stderr=subprocess.STDOUT)
 with tempfile.TemporaryDirectory(prefix='ctwr-payload-') as td:
  td=Path(td)
  for name,(sources,ld,folder,flags,assembly,relocs) in specs.items():
   b=td/name;b.mkdir();objects=[]
   for f in sources:
    obj=b/(Path(f).stem+'.o');objects.append(obj);source=SRC/folder/f
    if f in assembly:run('as','-mcpu=cortex-m7','-mthumb',source,'-o',obj)
    else:
     opts=flags or ['-mcpu=cortex-m7','-mthumb','-Os','-ffreestanding','-fno-builtin','-fstack-usage','-fno-unwind-tables','-fno-asynchronous-unwind-tables','-fno-stack-protector','-fno-pic']
     if name in ('s11b','s12a','s12b','s12c') and f.endswith('.c'):opts+=['-std=c11','-Wall','-Wextra','-Werror','-Wno-misleading-indentation']
     run('gcc',*opts,'-c',source,'-o',obj)
   elf=b/'payload.elf';run('ld',*(['--emit-relocs'] if relocs else ['--no-undefined']),'-T',SRC/folder/ld,*objects,'-o',elf)
   raw=b/'payload.bin';run('objcopy','-O','binary','-j','.text',elf,raw);data=raw.read_bytes()
   syms={}
   for line in run('nm','-n',elf).decode().splitlines():
    q=line.split()
    if len(q)==3 and q[1].lower() in ('t','r','d','b'):syms[q[2]]=int(q[0],16)
   settings=json.loads((SRC/name/'settings.json').read_text()) if name.startswith('s') else {}
   if name.startswith('s') and (len(data)!=settings['payload_bytes'] or hashlib.sha256(data).hexdigest()!=settings['payload_sha256']):raise SystemExit(name+' payload differs from reviewed map')
   out[name]={'hex':data.hex(),'sha256':hashlib.sha256(data).hexdigest(),'symbols':syms,'settings':settings}
 generated='// Generated by tools/export-wr2-payloads.py from project-owned sources.\nexport default '+json.dumps(out,separators=(',',':'))+';\n'
 if a.check:
  if OUT.read_text()!=generated:raise SystemExit('WR2 payload module is stale; regenerate and review')
 else:OUT.write_text(generated)
 print('WR2_PAYLOADS_PASS',hashlib.sha256(generated.encode()).hexdigest())
if __name__=='__main__':main()
